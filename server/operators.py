def add(a,b):
    """Permet d'additionner deux chiffres.

    Entrées:
        a: Première valeur numérique.
        b: Deuxième valeur numérique.

    Sortie:
        Somme de ``a`` et ``b``.
    """
    return a + b

def subtract(a,b):
    """Permet de soustraire la première valeur de la deuxième.

    Entrées:
        a: Valeur numérique soustraite.
        b: Valeur numérique de départ.

    Sortie:
        Différence ``b - a``.
    """
    return b - a

def multiply(a,b):
    """Permet de multiplier la première valeur par la deuxième.

    Entrées:
        a: Valeur numérique utilisée comme multiplicande.
        b: Valeur numérique utilisée comme multiplicateur.

    Sortie:
        Résultat de ``a`` multiplié par ``b``.
    """
    return a * b

def divide(a,b):
    """Effectue une division entière de la première valeur par la deuxième.

    Entrées:
        a: Dividende numérique.
        b: Diviseur numérique.

    Sortie:
        Quotient entier de ``a`` divisé par ``b``.
    """
    return a // b
