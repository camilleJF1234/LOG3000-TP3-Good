def add(a,b):
    """Permet d'additionner deux chiffres.

    Entrées:
        a: Première valeur numérique.
        b: Deuxième valeur numérique.

    Sortie:
        Somme de ``a`` et ``b``.
    """
    return a + b

def subtract(a,b):
    """Permet de soustraire la deuxième valeur de la première.

    Entrées:
        a: Valeur numérique de départ.
        b: Valeur numérique soustraite.

    Sortie:
        Différence ``a - b``.
    """
    return a - b

def multiply(a,b):
    """Permet de multiplier la première valeur par la deuxième.

    Entrées:
        a: Valeur numérique utilisée comme multiplicande.
        b: Valeur numérique utilisée comme multiplicateur.

    Sortie:
        Résultat de ``a`` multiplié par ``b``.
    """
    return a * b

def divide(a,b):
    """Effectue une division de la première valeur par la deuxième.

    Entrées:
        a: Dividende numérique.
        b: Diviseur numérique.

    Sortie:
        Quotient de ``a`` divisé par ``b``.
    """
    return a / b
